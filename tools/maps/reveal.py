"""Builds addon/MinistryOfTheAllied/MapReveal.lua: every Forever zone map's
pieces, so the add-on can draw a map with no fog of war (Hide and Seek's play
area). Nothing is copied but numbers: each piece is a texture already in the
game client, named by its file ID, with where it sits on its zone map.

The tables come from the game's own data for the Forever build, as wago.tools
exports them: WorldMapOverlay (each piece's size and place), WorldMapOverlayTile
(its 256-pixel tiles' file IDs) and UiMapXMapArt (which zone maps use which
art). Run it again when Forever updates:

    py -3.11 tools/maps/reveal.py 1.60.1.70888
"""
import csv
import io
import math
import os
import sys
import urllib.request
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "addon", "MinistryOfTheAllied", "MapReveal.lua")


def table(name, build):
    url = "https://wago.tools/db2/%s/csv?build=%s" % (name, build)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8"))))


def main(build):
    art_maps = defaultdict(set)
    for r in table("UiMapXMapArt", build):
        art_maps[int(r["UiMapArtID"])].add(int(r["UiMapID"]))
    tiles = defaultdict(list)
    for r in table("WorldMapOverlayTile", build):
        tiles[int(r["WorldMapOverlayID"])].append(r)
    by_map = defaultdict(list)
    for r in table("WorldMapOverlay", build):
        t = tiles[int(r["ID"])]
        art = int(r["UiMapArtID"])
        if not t or art not in art_maps:
            continue
        w, h = int(r["TextureWidth"]), int(r["TextureHeight"])
        nw, nh = math.ceil(w / 256), math.ceil(h / 256)
        files = [0] * (nw * nh)
        for x in t:
            if x["LayerIndex"] == "0":
                files[int(x["RowIndex"]) * nw + int(x["ColIndex"])] = int(x["FileDataID"])
        piece = "{%d,%d,%d,%d,%d,%d,{%s}}" % (int(r["OffsetX"]), int(r["OffsetY"]), w, h, nw, nh, ",".join(map(str, files)))
        for m in art_maps[art]:
            by_map[m].append(piece)
    lines = [
        "-- Ministry of the Allied: the zone maps with no fog of war (generated by",
        "-- tools/maps/reveal.py from the game's data for Forever %s; don't edit)." % build,
        "-- [uiMapID] = { { x, y, w, h, tiles wide, tiles tall, { file IDs, row by row } }, ... }",
        "",
        "local _, MOTA = ...",
        'MOTA.MapRevealBuild = "%s"' % build,
        "MOTA.MapReveal = {",
    ]
    for m in sorted(by_map):
        lines.append("  [%d] = { %s }," % (m, ", ".join(by_map[m])))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d maps, %d pieces -> %s" % (len(by_map), sum(len(v) for v in by_map.values()), os.path.normpath(OUT)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70888")
